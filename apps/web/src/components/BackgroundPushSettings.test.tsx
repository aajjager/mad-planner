import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { BackgroundPushSettings } from './BackgroundPushSettings'
import * as push from '../push'

const { setPreferences } = vi.hoisted(() => ({ setPreferences: vi.fn().mockResolvedValue(undefined) }))
vi.mock('../auth/AuthContext', () => ({ useAuth: () => ({ account: { id: 1, locale: 'en', browser_notifications_enabled: true }, setBrowserNotifications: setPreferences }) }))
vi.mock('../push', () => ({ pushSupported: vi.fn(() => true), pushConfig: vi.fn(), backgroundSubscribed: vi.fn(), enableBackgroundPush: vi.fn(), disableBackgroundPush: vi.fn() }))
afterEach(() => { cleanup(); vi.resetAllMocks(); vi.unstubAllGlobals() })
beforeEach(() => { vi.stubGlobal('Notification', { permission: 'default' }) })

describe('Background notification settings', () => {
  it('can pause existing account notifications even on an unsupported device', async () => {
    vi.mocked(push.pushSupported).mockReturnValue(false)
    setPreferences.mockResolvedValue(undefined)
    render(<BackgroundPushSettings />)
    const control = screen.getByRole('checkbox')
    expect(control).toBeChecked()
    expect(control).toBeEnabled()
    fireEvent.click(control)
    await waitFor(() => expect(setPreferences).toHaveBeenCalledWith(false))
    expect(push.disableBackgroundPush).not.toHaveBeenCalled()
  })
  it('shows administrator setup state without asking for browser permission', async () => {
    vi.mocked(push.pushSupported).mockReturnValue(true)
    vi.mocked(push.pushConfig).mockResolvedValue({ enabled: false, public_key: null })
    vi.mocked(push.backgroundSubscribed).mockResolvedValue(false)
    render(<BackgroundPushSettings />)
    expect(await screen.findByText(/administrator needs to configure/)).toBeVisible()
    expect(push.enableBackgroundPush).not.toHaveBeenCalled()
  })
  it('uses one switch to enable background delivery and disable the account preference', async () => {
    vi.mocked(push.pushSupported).mockReturnValue(true)
    vi.mocked(push.pushConfig).mockResolvedValue({ enabled: true, public_key: 'public-key' })
    vi.mocked(push.backgroundSubscribed).mockResolvedValue(false)
    vi.mocked(push.enableBackgroundPush).mockResolvedValue(true)
    setPreferences.mockResolvedValue(undefined)
    render(<BackgroundPushSettings />)
    const enable = screen.getByRole('checkbox', { name: /Phone and browser notifications/ })
    await waitFor(() => expect(enable).toBeEnabled())
    fireEvent.click(enable)
    await waitFor(() => expect(enable).toBeChecked())
    fireEvent.click(enable)
    await waitFor(() => expect(push.disableBackgroundPush).toHaveBeenCalledOnce())
    expect(setPreferences).toHaveBeenCalledWith(true)
    expect(setPreferences).toHaveBeenCalledWith(false)
    expect(screen.getAllByRole('checkbox')).toHaveLength(1)
    await waitFor(() => expect(enable).not.toBeChecked())
  })
  it('preserves an existing registration without asking for permission again', async () => {
    vi.mocked(push.pushSupported).mockReturnValue(true)
    vi.mocked(push.pushConfig).mockResolvedValue({ enabled: true, public_key: 'public-key' })
    vi.mocked(push.backgroundSubscribed).mockResolvedValue(true)
    render(<BackgroundPushSettings />)
    await waitFor(() => expect(screen.getByRole('checkbox')).toBeChecked())
    expect(push.enableBackgroundPush).not.toHaveBeenCalled()
  })
  it('automatically upgrades an existing opt-in only when permission is already granted', async () => {
    vi.stubGlobal('Notification', { permission: 'granted' })
    vi.mocked(push.pushSupported).mockReturnValue(true)
    vi.mocked(push.pushConfig).mockResolvedValue({ enabled: true, public_key: 'public-key' })
    vi.mocked(push.backgroundSubscribed).mockResolvedValue(false)
    vi.mocked(push.enableBackgroundPush).mockResolvedValue(true)
    render(<BackgroundPushSettings />)
    await waitFor(() => expect(screen.getByRole('checkbox')).toBeChecked())
    expect(push.enableBackgroundPush).toHaveBeenCalledWith('public-key')
  })
  it('keeps the switch off after denied permission and does not enable preferences', async () => {
    vi.stubGlobal('Notification', { permission: 'default' })
    vi.mocked(push.pushSupported).mockReturnValue(true)
    vi.mocked(push.pushConfig).mockResolvedValue({ enabled: true, public_key: 'public-key' })
    vi.mocked(push.backgroundSubscribed).mockResolvedValue(false)
    vi.mocked(push.enableBackgroundPush).mockResolvedValue(false)
    render(<BackgroundPushSettings />)
    const control = screen.getByRole('checkbox')
    await waitFor(() => expect(control).toBeEnabled())
    fireEvent.click(control)
    await screen.findByRole('alert')
    expect(control).not.toBeChecked()
    expect(setPreferences).not.toHaveBeenCalled()
  })
  it('pauses server notifications even if browser unsubscription fails', async () => {
    vi.mocked(push.pushSupported).mockReturnValue(true)
    vi.mocked(push.pushConfig).mockResolvedValue({ enabled: true, public_key: 'public-key' })
    vi.mocked(push.backgroundSubscribed).mockResolvedValue(true)
    setPreferences.mockResolvedValue(undefined)
    vi.mocked(push.disableBackgroundPush).mockRejectedValue(new Error('offline'))
    render(<BackgroundPushSettings />)
    const control = screen.getByRole('checkbox')
    await waitFor(() => expect(control).toBeChecked())
    fireEvent.click(control)
    await screen.findByRole('alert')
    expect(setPreferences).toHaveBeenCalledWith(false)
    expect(control).not.toBeChecked()
  })
})
